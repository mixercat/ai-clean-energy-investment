def _norm(s):
    return re.sub(r"\s+", "", (s or "").lower())


def select_knowledge(question, max_sections=3, always=()):
    """เลือกหัวข้อที่เกี่ยวกับคำถามที่สุด (นับคำสำคัญที่พบ) -> list ของ section"""
    q = _norm(question)
    scored = []
    for sec in SECTIONS:
        hits = sum(1 for k in sec["keywords"] if _norm(k) in q)
        if hits or sec["id"] in always:
            scored.append((hits + (0.5 if sec["id"] in always else 0), sec))
    scored.sort(key=lambda x: -x[0])
    return [s for _, s in scored[:max_sections]]


def knowledge_text(question, max_sections=3):
    secs = select_knowledge(question, max_sections)
    if not secs:
        return ""
    parts = ["คลังความรู้ที่เกี่ยวข้อง (ใช้ตอบได้ และบอกที่มาอย่างสั้น):"]
    for s in secs:
        parts.append(f"### {s['title']}\n{s['text']}\n(ที่มา: {s['source']})")
    return "\n\n".join(parts)


def topics():
    return [s["title"] for s in SECTIONS]
